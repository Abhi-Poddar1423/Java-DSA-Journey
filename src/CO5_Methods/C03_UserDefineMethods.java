package CO5_Methods;

public class C03_UserDefineMethods {

    // This is a user-defined method created by the programmer.
    // 'void' means this method does not return any value.
    // 'greet' is the name of the method.

    public static void greet(){
        System.out.println("Hello,Welcome to Java!");
    }
    public static void main(String[] args){

        // Calling the user-defined 'greet()' method.
        // When this method is called, its statements are executed

        greet();
    }


}
